CREATE OR REPLACE FUNCTION fn_confirmar_pedido_descontar_stock()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_tipo_venta BIGINT;
    v_stock NUMERIC(12,3);
    v_requerido NUMERIC(12,3);
    v_producto_id BIGINT;
BEGIN
    IF NOT fn_catalogo_valor_es(NEW.estado_id, 'ESTADO_PEDIDO', 'CONFIRMADO') THEN
        RETURN NEW;
    END IF;

    SELECT cv.id
      INTO v_tipo_venta
      FROM catalogo_valores cv
      JOIN catalogo_conceptos cc ON cc.id = cv.concepto_id
     WHERE cc.codigo = 'TIPO_MOVIMIENTO'
       AND cv.codigo = 'VENTA'
       AND cc.activo = TRUE
       AND cv.activo = TRUE;

    IF v_tipo_venta IS NULL THEN
        RAISE EXCEPTION 'No existe el tipo de movimiento VENTA activo';
    END IF;

    -- Primero se bloquean y validan TODAS las existencias. Si una falla, la
    -- transaccion completa se revierte, incluida la aprobacion de la proforma.
    FOR v_producto_id, v_requerido IN
        SELECT pd.producto_id, SUM(pd.cantidad)::NUMERIC(12,3)
          FROM proformas_detalle pd
         WHERE pd.proforma_id = NEW.proforma_id
           AND pd.producto_id IS NOT NULL
         GROUP BY pd.producto_id
         ORDER BY pd.producto_id
    LOOP
        SELECT stock
          INTO v_stock
          FROM productos
         WHERE id = v_producto_id
         FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Producto % no existe', v_producto_id;
        END IF;

        IF v_stock < v_requerido THEN
            RAISE EXCEPTION 'No se puede aprobar la proforma: stock insuficiente para producto %. Disponible: %, requerido: %',
                v_producto_id, v_stock, v_requerido;
        END IF;
    END LOOP;

    -- Solo despues de validar todo el pedido se crean las salidas.
    FOR v_producto_id, v_requerido IN
        SELECT pd.producto_id, SUM(pd.cantidad)::NUMERIC(12,3)
          FROM proformas_detalle pd
         WHERE pd.proforma_id = NEW.proforma_id
           AND pd.producto_id IS NOT NULL
         GROUP BY pd.producto_id
         ORDER BY pd.producto_id
    LOOP
        INSERT INTO movimientos_stock (
            producto_id,
            fecha,
            tipo_movimiento_id,
            cantidad,
            pedido_id,
            observaciones,
            created_by_id
        ) VALUES (
            v_producto_id,
            CURRENT_TIMESTAMP,
            v_tipo_venta,
            -v_requerido,
            NEW.id,
            'Salida por aprobacion de proforma y confirmacion del pedido #' || NEW.id,
            COALESCE(NEW.updated_by_id, NEW.created_by_id)
        );
    END LOOP;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_confirmar_pedido_descontar_stock
AFTER INSERT ON pedidos
FOR EACH ROW
EXECUTE FUNCTION fn_confirmar_pedido_descontar_stock();

-- La aprobacion de la proforma es el evento empresarial que crea el pedido.
-- Si la creacion del pedido o cualquier salida de stock falla, la excepcion
-- revierte tambien el cambio de estado de la proforma.
CREATE OR REPLACE FUNCTION fn_aprobar_proforma_crear_pedido()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_estado_confirmado BIGINT;
BEGIN
    IF NOT fn_catalogo_valor_es(NEW.estado_id, 'ESTADO_PROFORMA', 'APROBADA')
       OR fn_catalogo_valor_es(OLD.estado_id, 'ESTADO_PROFORMA', 'APROBADA') THEN
        RETURN NEW;
    END IF;

    IF EXISTS (SELECT 1 FROM pedidos pe WHERE pe.proforma_id = NEW.id) THEN
        RAISE EXCEPTION 'La proforma % ya tiene un pedido asociado', NEW.id;
    END IF;

    SELECT cv.id
      INTO v_estado_confirmado
      FROM catalogo_valores cv
      JOIN catalogo_conceptos cc ON cc.id = cv.concepto_id
     WHERE cc.codigo = 'ESTADO_PEDIDO'
       AND cv.codigo = 'CONFIRMADO'
       AND cc.activo = TRUE
       AND cv.activo = TRUE;

    IF v_estado_confirmado IS NULL THEN
        RAISE EXCEPTION 'No existe el estado CONFIRMADO activo para pedidos';
    END IF;

    INSERT INTO pedidos (
        proforma_id,
        fecha_confirmacion,
        estado_id,
        created_by_id,
        updated_by_id
    ) VALUES (
        NEW.id,
        CURRENT_TIMESTAMP,
        v_estado_confirmado,
        COALESCE(NEW.updated_by_id, NEW.created_by_id),
        COALESCE(NEW.updated_by_id, NEW.created_by_id)
    );

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_aprobar_proforma_crear_pedido
AFTER UPDATE OF estado_id ON proformas
FOR EACH ROW
EXECUTE FUNCTION fn_aprobar_proforma_crear_pedido();

