-- ============================================================================
-- 16. VALIDACION DE DETALLES Y ESPECIFICACIONES DE MUEBLES
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_validar_proforma_detalle()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_tipo TEXT;
    v_categoria TEXT;
    v_unidad TEXT;
    v_unidad_producto BIGINT;
BEGIN
    IF NOT fn_catalogo_valor_pertenece(NEW.tipo_item_id, 'TIPO_ITEM') THEN
        RAISE EXCEPTION 'tipo_item_id % no pertenece a TIPO_ITEM activo', NEW.tipo_item_id;
    END IF;
    IF NOT fn_catalogo_valor_pertenece(NEW.unidad_id, 'UNIDAD_MEDIDA') THEN
        RAISE EXCEPTION 'unidad_id % no pertenece a UNIDAD_MEDIDA activa', NEW.unidad_id;
    END IF;

    v_tipo := fn_catalogo_codigo_valor(NEW.tipo_item_id, 'TIPO_ITEM');
    v_unidad := fn_catalogo_codigo_valor(NEW.unidad_id, 'UNIDAD_MEDIDA');

    IF v_tipo = 'MUEBLE_MEDIDA' THEN
        IF NEW.producto_id IS NOT NULL THEN
            RAISE EXCEPTION 'Un MUEBLE_MEDIDA no debe apuntar a PRODUCTOS';
        END IF;
        IF v_unidad <> 'PIEZA' THEN
            RAISE EXCEPTION 'Un MUEBLE_MEDIDA debe cotizarse en PIEZA';
        END IF;
    ELSE
        IF NEW.producto_id IS NULL THEN
            RAISE EXCEPTION 'El tipo de item % requiere producto_id', v_tipo;
        END IF;

        SELECT fn_catalogo_codigo_valor(p.categoria_id, 'CATEGORIA_PRODUCTO'), p.unidad_stock_id
          INTO v_categoria, v_unidad_producto
          FROM productos p
         WHERE p.id = NEW.producto_id
           AND p.activo = TRUE;

        IF v_categoria IS NULL THEN
            RAISE EXCEPTION 'Producto % no existe, esta inactivo o tiene una categoria invalida', NEW.producto_id;
        END IF;

        IF v_tipo = 'SILLA' AND v_categoria <> 'SILLA' THEN
            RAISE EXCEPTION 'El item SILLA debe utilizar un producto de categoria SILLA';
        ELSIF v_tipo = 'PISO_FLOTANTE' AND v_categoria <> 'PISO_FLOTANTE' THEN
            RAISE EXCEPTION 'El item PISO_FLOTANTE debe utilizar un producto de categoria PISO_FLOTANTE';
        ELSIF v_tipo = 'OTRO' AND v_categoria <> 'OTRO' THEN
            RAISE EXCEPTION 'El item OTRO debe utilizar un producto de categoria OTRO';
        END IF;

        IF v_tipo = 'SILLA' AND NOT EXISTS (SELECT 1 FROM productos_silla ps WHERE ps.producto_id = NEW.producto_id) THEN
            RAISE EXCEPTION 'El producto SILLA % no tiene su ficha en productos_silla', NEW.producto_id;
        ELSIF v_tipo = 'PISO_FLOTANTE' AND NOT EXISTS (SELECT 1 FROM productos_piso pp WHERE pp.producto_id = NEW.producto_id) THEN
            RAISE EXCEPTION 'El producto PISO_FLOTANTE % no tiene su ficha en productos_piso', NEW.producto_id;
        END IF;

        IF NEW.unidad_id <> v_unidad_producto THEN
            RAISE EXCEPTION 'La unidad de venta del producto debe coincidir con su unidad de stock';
        END IF;

        IF v_tipo = 'PISO_FLOTANTE' AND v_unidad <> 'CAJA' THEN
            RAISE EXCEPTION 'Los pisos se venden exclusivamente por CAJA';
        ELSIF v_tipo IN ('SILLA', 'OTRO') AND v_unidad <> 'PIEZA' THEN
            RAISE EXCEPTION 'Los items % se venden en PIEZA', v_tipo;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

