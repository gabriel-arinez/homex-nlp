CREATE OR REPLACE FUNCTION fn_catalogo_valor_pertenece(
    p_valor_id BIGINT,
    p_concepto_codigo VARCHAR
) RETURNS BOOLEAN
LANGUAGE SQL
STABLE
AS $$
    SELECT EXISTS (
        SELECT 1
          FROM catalogo_valores cv
          JOIN catalogo_conceptos cc ON cc.id = cv.concepto_id
         WHERE cv.id = p_valor_id
           AND cc.codigo = p_concepto_codigo
           AND cc.activo = TRUE
           AND cv.activo = TRUE
    );
$$;

CREATE OR REPLACE FUNCTION fn_catalogo_valor_es(
    p_valor_id BIGINT,
    p_concepto_codigo VARCHAR,
    p_valor_codigo VARCHAR
) RETURNS BOOLEAN
LANGUAGE SQL
STABLE
AS $$
    SELECT EXISTS (
        SELECT 1
          FROM catalogo_valores cv
          JOIN catalogo_conceptos cc ON cc.id = cv.concepto_id
         WHERE cv.id = p_valor_id
           AND cc.codigo = p_concepto_codigo
           AND cv.codigo = p_valor_codigo
           AND cc.activo = TRUE
           AND cv.activo = TRUE
    );
$$;

CREATE OR REPLACE FUNCTION fn_catalogo_codigo_valor(
    p_valor_id BIGINT,
    p_concepto_codigo VARCHAR
) RETURNS TEXT
LANGUAGE SQL
STABLE
AS $$
    SELECT cv.codigo
      FROM catalogo_valores cv
      JOIN catalogo_conceptos cc ON cc.id = cv.concepto_id
     WHERE cv.id = p_valor_id
       AND cc.codigo = p_concepto_codigo
       AND cc.activo = TRUE
       AND cv.activo = TRUE;
$$;

