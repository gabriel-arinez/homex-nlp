CREATE INDEX ix_notas_entrega_fecha ON notas_entrega(fecha);

-- ============================================================================
-- 8. RECIBOS DIGITALES (SE GUARDAN DATOS, NO EL DOCUMENTO GENERADO)
-- ============================================================================

CREATE TABLE recibos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero           BIGINT NOT NULL UNIQUE,
    proforma_id      BIGINT NOT NULL REFERENCES proformas(id),
    nombre_completo  VARCHAR(250) NOT NULL,
    monto_en_letras  TEXT NOT NULL,
    concepto         TEXT NOT NULL,
    tipo_pago_id     BIGINT NOT NULL REFERENCES catalogo_valores(id),
    numero_cheque    VARCHAR(80),
    banco            VARCHAR(150),
    total            NUMERIC(14,2) NOT NULL,
    a_cuenta         NUMERIC(14,2),
    saldo            NUMERIC(14,2),
    fecha            DATE NOT NULL DEFAULT CURRENT_DATE,
    created_by_id    BIGINT,
    updated_by_id    BIGINT,
    CONSTRAINT ck_recibo_total_positive CHECK (total > 0),
    CONSTRAINT ck_recibo_a_cuenta_nonnegative CHECK (a_cuenta IS NULL OR a_cuenta >= 0),
    CONSTRAINT ck_recibo_saldo_nonnegative CHECK (saldo IS NULL OR saldo >= 0)
);

CREATE INDEX ix_recibos_proforma ON recibos(proforma_id);
CREATE INDEX ix_recibos_fecha ON recibos(fecha);
CREATE INDEX ix_recibos_tipo_pago ON recibos(tipo_pago_id);

-- La moneda del recibo NO se almacena: se obtiene siempre desde proformas.moneda_id.

