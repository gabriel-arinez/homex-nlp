-- productos.stock es una proyeccion de movimientos_stock. No se permite crear
-- un producto con stock inicial distinto de cero ni modificar stock directamente.
CREATE OR REPLACE FUNCTION fn_proteger_stock_producto()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_contexto TEXT;
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.stock <> 0 THEN
            RAISE EXCEPTION 'El stock inicial de un producto debe ser 0. Use un movimiento CARGA_INICIAL';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.stock IS DISTINCT FROM OLD.stock THEN
        v_contexto := current_setting('homex.stock_update_context', TRUE);
        IF COALESCE(v_contexto, '') <> 'MOVIMIENTO_STOCK' THEN
            RAISE EXCEPTION 'productos.stock no puede modificarse directamente. Registre un movimiento de stock';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

